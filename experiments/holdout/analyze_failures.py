"""Generate FAILURE_ANALYSIS.md from a holdout run's per_report.jsonl (deterministic; nothing is hand-edited).

    python experiments/holdout/analyze_failures.py [--dir experiments/results/holdout] [--holdout data/holdout]

Lists every safety failure (a report that must not compile, but did), every supported report that was not compiled
correctly with the reason the product gave, and the raw model's silent errors - with the report text, so a reader can
judge each one.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))
from sentinelforge.pipeline import analyze  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", type=Path, default=REPO / "experiments" / "results" / "holdout")
    ap.add_argument("--holdout", type=Path, default=REPO / "data" / "holdout")
    a = ap.parse_args()
    rows = [json.loads(l) for l in (a.dir / "per_report.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    manifest = {e["reportId"]: e for e in json.loads((a.holdout / "manifest.json").read_text(encoding="utf-8"))["entries"]}
    text = lambda rid: (a.holdout / "reports" / f"{rid}.md").read_text(encoding="utf-8").strip()  # noqa: E731
    out = ["# Failure analysis (generated)\n",
           f"Source: `{a.dir.relative_to(REPO).as_posix()}/per_report.jsonl`. Generated by `experiments/holdout/analyze_failures.py`; "
           "nothing here is edited by hand.\n"]

    out.append("## 1. Safety failures: reports that must NOT compile, but did\n")
    for system in ("finetuned+evidence", "evidence-only", "regex+evidence"):
        bad = [r for r in rows if r["system"] == system and r["expect"] == "no_compile" and r.get("falseAccept")]
        out.append(f"### {system}: {len(bad)} of {sum(1 for r in rows if r['system'] == system and r['expect'] == 'no_compile')}\n")
        for r in bad:
            out.append(f"- **{r['reportId']}** ({r['reasonClass']}) -> compiled as `{r['decidedBehaviour']}`\n\n  > {text(r['reportId']).replace(chr(10), ' ')[:400]}\n")

    out.append("\n## 2. Supported reports that were not compiled correctly (evidence-only path, with the product's reason)\n")
    by = defaultdict(list)
    for r in rows:
        if r["system"] == "evidence-only" and r["expect"] == "compiled" and not r.get("completeCorrect"):
            an = analyze(text(r["reportId"]), None)
            by[f"{an.status}: {', '.join(sorted(set(an.reconciliation.codes)))}"].append(r["reportId"])
    for k, ids in sorted(by.items(), key=lambda kv: -len(kv[1])):
        out.append(f"- **{len(ids)}x `{k}`**: {', '.join(ids)}\n")

    out.append("\n## 3. Success rate by writing style (supported reports)\n")
    out.append("| style | n | evidence-only correct | fine-tuned + evidence correct | fine-tuned raw correct | fine-tuned raw silently wrong |\n|---|---|---|---|---|---|\n")
    per = defaultdict(lambda: defaultdict(lambda: [0, 0]))
    for r in rows:
        if r["expect"] != "compiled":
            continue
        st = manifest[r["reportId"]]["style"]
        per[st][r["system"]][0] += 1
        per[st][r["system"]][1] += int(bool(r.get("completeCorrect")))
        if r["system"] == "finetuned-raw":
            per[st]["_wrong"][1] += int(bool(r.get("wrongSilent")))
    for st, d in sorted(per.items()):
        n = d["evidence-only"][0]
        out.append(f"| {st} | {n} | {d['evidence-only'][1]} | {d['finetuned+evidence'][1]} | {d['finetuned-raw'][1]} | {d['_wrong'][1]} |\n")

    out.append("\n## 4. The raw fine-tuned model's silent errors (no evidence check)\n")
    wrong = [r for r in rows if r["system"] == "finetuned-raw" and r.get("wrongSilent")]
    causes = Counter()
    for r in wrong:
        causes["wrong behaviour" if not r.get("behaviourCorrect") else "wrong count" if r.get("countCorrect") is False else "wrong window" if r.get("windowCorrect") is False else "other"] += 1
    out.append(f"{len(wrong)} of {sum(1 for r in rows if r['system'] == 'finetuned-raw' and r['expect'] == 'compiled')} supported reports compiled to a WRONG rule. Causes: "
               + ", ".join(f"{v}x {k}" for k, v in causes.most_common()) + ".\n")
    (a.dir / "FAILURE_ANALYSIS.md").write_text("".join(out), encoding="utf-8")
    print("wrote", a.dir / "FAILURE_ANALYSIS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
